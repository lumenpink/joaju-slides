use crate::error::SlidesError;
use crate::model::SlideDeck;

pub fn render_slides_typst(deck: &SlideDeck) -> Result<String, SlidesError> {
    let mut out = String::new();
    let paper = deck.aspect_ratio.typst_paper();

    out.push_str(&format!(
        r#"// Generated by joaju-slides
#set page(
  paper: "{paper}",
  margin: (x: 2cm, y: 1.5cm)
)
#set text(font: "Liberation Sans", size: 28pt)
#set align(center + horizon)

"#
    ));

    for (idx, slide) in deck.slides.iter().enumerate() {
        if idx > 0 {
            out.push_str("\n#pagebreak()\n\n");
        }

        // Format visual content
        let clean_content = sanitize_markdown_to_typst(&slide.visual_content);
        out.push_str(&clean_content);
        out.push('\n');
    }

    if let Some(ref bib) = deck.bibliography {
        out.push_str("\n#pagebreak()\n\n");
        out.push_str(&format!(
            "#align(center + horizon)[\n  #text(size: 14pt)[\n    #bibliography(\"{}\", style: \"{}\")\n  ]\n]\n",
            bib.display(),
            deck.bib_style
        ));
    }

    Ok(out)
}

pub fn render_handout_typst(deck: &SlideDeck) -> Result<String, SlidesError> {
    let mut out = String::new();

    out.push_str(
        r#"// Generated by joaju-slides (Handout Mode)
#set page(
  paper: "a4",
  margin: 2cm,
  header: locate(loc => {
    // Micro-header on pages
  })
)
#set text(font: "Liberation Sans", size: 11pt)
#set par(justify: true)

"#,
    );

    for (idx, slide) in deck.slides.iter().enumerate() {
        if idx > 0 {
            out.push_str("\n#pagebreak()\n\n");
        }

        let default_title = format!("Lâmina {}", slide.slide_index);
        let title = slide.title_hint.as_deref().unwrap_or(&default_title);
        let visual = sanitize_markdown_to_typst(&slide.visual_content);

        out.push_str(&format!(
            r#"#block(
  width: 100%,
  stroke: 0.5pt + luma(180),
  inset: 10pt,
  radius: 3pt,
  fill: luma(250)
)[
  #align(center)[
    #text(weight: "bold", size: 12pt)[{title}]
    #v(0.5em)
    #text(size: 10pt)[{visual}]
  ]
]

#v(1em)
#line(length: 100%, stroke: 0.5pt + luma(200))
#v(0.5em)

"#
        ));

        if let Some(ref notes) = slide.speaker_notes {
            let clean_notes = sanitize_markdown_to_typst(notes);
            out.push_str(&clean_notes);
            out.push('\n');
        }

        out.push_str(&format!(
            r#"
#align(right)[#text(size: 8pt, fill: luma(120), italic: true)[(Continuação das notas - Lâmina {}: {})]]
"#,
            slide.slide_index, title
        ));
    }

    if let Some(ref bib) = deck.bibliography {
        out.push_str("\n#pagebreak()\n\n");
        out.push_str(&format!(
            "= Referências Bibliográficas\n\n#bibliography(\"{}\", style: \"{}\")\n",
            bib.display(),
            deck.bib_style
        ));
    }

    Ok(out)
}

pub fn render_notes_typst(deck: &SlideDeck) -> Result<String, SlidesError> {
    let mut out = String::new();

    out.push_str(&format!(
        r#"// Generated by joaju-slides (Notes Mode)
#set page(
  paper: "a4",
  margin: 2.5cm,
  footer: locate(loc => align(center)[#counter(page).display("1")])
)
#set text(font: "Liberation Sans", size: 11pt)
#set par(justify: true)

= {}

"#,
        deck.title
    ));

    for slide in &deck.slides {
        let default_title = format!("Lâmina {}", slide.slide_index);
        let title = slide.title_hint.as_deref().unwrap_or(&default_title);

        out.push_str(&format!("= {title}\n\n"));

        if let Some(ref notes) = slide.speaker_notes {
            let clean_notes = sanitize_markdown_to_typst(notes);
            out.push_str(&clean_notes);
            out.push_str("\n\n");
        }
    }

    if let Some(ref bib) = deck.bibliography {
        out.push_str(&format!(
            "= Referências\n\n#bibliography(\"{}\", style: \"{}\")\n",
            bib.display(),
            deck.bib_style
        ));
    }

    Ok(out)
}

fn sanitize_markdown_to_typst(input: &str) -> String {
    let mut lines = Vec::new();

    for line in input.lines() {
        let trimmed = line.trim();
        // Handle images ![[image.ext]] -> #image("image.ext", height: 70%, fit: "contain")
        if let Some(stripped) = trimmed
            .strip_prefix("![[")
            .and_then(|s| s.strip_suffix("]]"))
        {
            lines.push(format!(
                r#"#image("{}", height: 70%, fit: "contain")"#,
                stripped
            ));
        } else if let Some(h1) = trimmed.strip_prefix("# ") {
            lines.push(format!("= {}", h1));
        } else if let Some(h2) = trimmed.strip_prefix("## ") {
            lines.push(format!("== {}", h2));
        } else if let Some(h3) = trimmed.strip_prefix("### ") {
            lines.push(format!("=== {}", h3));
        } else {
            lines.push(line.to_string());
        }
    }

    lines.join("\n")
}
